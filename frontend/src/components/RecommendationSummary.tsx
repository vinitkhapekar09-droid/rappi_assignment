import type { Recommendation } from '../api/types'
import { decisionLabel, formatDateTime, formatMoney, formatNumber } from '../utils/format'
import { Panel } from './Panel'
import { StatusPill, type Tone } from './StatusPill'
import { isExecutable } from '../workflow/state'

const DECISION_TONE: Record<Recommendation['decision'], Tone> = {
  accept: 'success',
  modify: 'warning',
  reject: 'danger',
  investigate: 'warning',
}

export function RecommendationSummary({ recommendation }: { recommendation: Recommendation }) {
  return (
    <Panel
      title="Recommendation"
      subtitle={`Version ${recommendation.version_number} · generated by ${recommendation.generated_by}`}
      actions={<StatusPill tone={isExecutable(recommendation) ? DECISION_TONE[recommendation.decision] : 'warning'}>{
        ['accept', 'modify'].includes(recommendation.decision) && !isExecutable(recommendation)
          ? 'Purchase blocked' : decisionLabel(recommendation.decision)
      }</StatusPill>}
    >
      <div className="metric-row">
        <Metric label="Initial recommendation" value={`${formatNumber(recommendation.initial_recommended_quantity)} units`} />
        <Metric
          label="Calculated requirement"
          value={
            recommendation.baseline_required_quantity === null
              ? 'Not computable'
              : `${formatNumber(recommendation.baseline_required_quantity)} units`
          }
          note="max(0, forecast + safety − inventory − eligible incoming)"
        />
        <Metric
          label="Recommended quantity"
          value={
            recommendation.recommended_quantity === null
              ? 'No order proposed'
              : `${formatNumber(recommendation.recommended_quantity)} units`
          }
          highlight
        />
      </div>

      <dl className="meta-grid">
        <Meta label="Supplier" value={recommendation.supplier_name ?? '—'} />
        <Meta label="Unit price" value={formatMoney(recommendation.unit_price, recommendation.currency)} />
        <Meta label="Total cost" value={formatMoney(recommendation.total_cost, recommendation.currency)} />
        <Meta label="MOQ" value={recommendation.moq === null || recommendation.moq === undefined ? '—' : formatNumber(recommendation.moq)} />
        <Meta label="Lead time" value={recommendation.lead_time_days === null || recommendation.lead_time_days === undefined ? '—' : `${recommendation.lead_time_days} days`} />
        <Meta label="Eligible incoming supply" value={`${formatNumber(recommendation.evidence?.eligible_incoming_quantity ?? null)} units`} />
        <Meta label="Inputs fingerprint" value={recommendation.inputs_fingerprint ?? '—'} mono />
        <Meta label="Generated" value={formatDateTime(recommendation.created_at)} />
      </dl>
    </Panel>
  )
}

function Metric({ label, value, note, highlight }: { label: string; value: string; note?: string; highlight?: boolean }) {
  return (
    <div className={`metric${highlight ? ' metric--highlight' : ''}`}>
      <span className="metric__label">{label}</span>
      <span className="metric__value">{value}</span>
      {note ? <span className="metric__note">{note}</span> : null}
    </div>
  )
}

function Meta({ label, value, mono }: { label: string; value: string | number; mono?: boolean }) {
  return (
    <div className="meta">
      <dt>{label}</dt>
      <dd className={mono ? 'mono' : undefined}>{value}</dd>
    </div>
  )
}
